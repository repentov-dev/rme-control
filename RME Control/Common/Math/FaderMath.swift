    private static let positionFromDB = MonotoneCubicSpline(points: curve.map { ($0.1, $0.0) })
    private static let dbFromPosition = MonotoneCubicSpline(points: curve)

    static func db(for value: Double) -> Double {
        let p = min(max(value, 0), 1)
        var lo = 0
        var hi = curve.count - 1
        if p <= curve[0].0 { return curve[0].1 }
        if p >= curve[hi].0 { return curve[hi].1 }
        while lo + 1 < hi {
            let mid = (lo + hi) / 2
            if curve[mid].0 <= p { lo = mid } else { hi = mid }
        }
        let (p0, d0) = curve[lo]
        let (p1, d1) = curve[hi]
        return d0 + (d1 - d0) * (p - p0) / (p1 - p0)
    }

    static func position(forDB db: Double) -> Double {
        min(max(positionFromDB.interpolate(db), 0), 1)
    }
